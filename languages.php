function __t($key, $lang = 'tr') {
    global $translations;
    $lang = strtolower($lang);
    if (!isset($translations[$lang])) {
        $lang = 'tr';
    }
    return $translations[$lang][$key] ?? $translations['tr'][$key] ?? $key;
}

function getLocalizedText($item, $field, $lang = 'tr') {
    $lang = strtolower($lang);
    if ($lang === 'tr' || empty($lang)) {
        return $item[$field] ?? '';
    }
    $localizedKey = $field . '_' . $lang;
    if (!empty($item[$localizedKey])) {
        return $item[$localizedKey];
    }
    return $item[$field] ?? '';
}
